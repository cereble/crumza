import { execFileSync } from 'node:child_process';
import { readFileSync, rmSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { build } from 'esbuild';
import { brandSheet } from '../src/brand/css.ts';
import { SPRING, springEasing } from '../src/motion/spring.ts';

const root = new URL('../', import.meta.url);
const path = (relative: string): string => new URL(relative, root).pathname;

rmSync(path('dist'), { recursive: true, force: true });

// The live brand: --cz-brand-* variables in, every colour scale out, computed by the browser.
writeFileSync(path('src/styles/brand.css'), brandSheet());

// The CSS spring tokens are baked from the same springs the script uses, so both move alike.
const springs = (['snappy', 'smooth', 'lively', 'pop'] as const).map((name) => {
  const { duration, easing } = springEasing(SPRING[name]);
  return `  --cz-${name}: ${duration}ms ${easing};`;
});
writeFileSync(
  path('src/styles/springs.css'),
  `/* Generated by scripts/build.ts from SPRING in src/motion/spring.ts. Do not edit. */\n:root {\n${springs.join('\n')}\n}\n`,
);

// Modern browsers only, so nothing is lowered: light-dark(), nesting, @layer and @property stay as written.
const target = ['chrome123', 'edge123', 'safari17.5', 'firefox128'];
for (const minify of [false, true]) {
  await build({
    entryPoints: { [minify ? 'crumza.min' : 'crumza']: path('src/styles/crumza.css') },
    bundle: true,
    minify,
    target,
    outdir: path('dist'),
    logLevel: 'warning',
  });
}

execFileSync(path('../../node_modules/.bin/tsc'), ['-p', path('tsconfig.build.json')], { stdio: 'inherit' });

const size = (file: string): string => {
  const bytes = readFileSync(path(`dist/${file}`));
  return `${file} ${(bytes.length / 1024).toFixed(1)} kB, ${(gzipSync(bytes).length / 1024).toFixed(1)} kB gzipped`;
};
console.log(['crumza.css', 'crumza.min.css', 'brand/index.js', 'motion/index.js'].map(size).join('\n'));
